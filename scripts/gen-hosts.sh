#!/usr/bin/env bash
# =============================================================================
# 生成 /etc/hosts 片段：把网关域名指到本机（或指定 IP）
#
#   用法：
#     scripts/gen-hosts.sh                 # 自动探测本机局域网 IP，打印片段
#     scripts/gen-hosts.sh 192.168.0.50    # 指定 IP（局域网其他机器用这个）
#     scripts/gen-hosts.sh --write         # 直接写入 /etc/hosts（需 sudo）
#
#   为什么要 hosts 而不是 DNS：dnsmasq 只服务容器内部，
#   宿主机和局域网机器用 hosts 片段最省事，也不用改路由器 DNS。
# =============================================================================
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="${ENV_FILE:-$ROOT/.env}"
ROUTES="$ROOT/config/routes.yaml"

domain=""
[[ -f "$ENV_FILE" ]] && domain="$(sed -n 's/^GATEWAY_DOMAIN=//p' "$ENV_FILE" | tail -1 | tr -d '\042\047' | tr -d '[:space:]')"
domain="${GATEWAY_DOMAIN:-${domain:-org-devops.com}}"

ip=""
write=0
for arg in "$@"; do
    case "$arg" in
        --write) write=1 ;;
        -h|--help) sed -n '2,16p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) ip="$arg" ;;
    esac
done

# 没指定就猜：默认路由的源地址（Linux）/ 第一个非回环 IPv4（兜底）
if [[ -z "$ip" ]]; then
    ip="$(ip route get 1.1.1.1 2>/dev/null | sed -n 's/.* src \([0-9.]*\).*/\1/p' | head -1 || true)"
fi
if [[ -z "$ip" ]] && command -v ipconfig >/dev/null 2>&1; then
    ip="$(ipconfig 2>/dev/null | sed -n 's/.*IPv4.*: *\([0-9.]*\).*/\1/p' | head -1 || true)"
fi
ip="${ip:-127.0.0.1}"

# 从 routes.yaml 取全部 subdomain（保持文件顺序）
# 注意：不能对多行流用 tr -d '[:space:]' —— 它会把换行也删掉，5 个域名粘成一行。
mapfile -t subs < <(sed -n 's/^[[:space:]]*subdomain:[[:space:]]*//p' "$ROUTES" \
    | sed -e 's/[[:space:]]*$//' -e 's/^["'\'']//' -e 's/["'\'']$//' \
    | grep -v '^$')
[[ ${#subs[@]} -gt 0 ]] || { echo "从 $ROUTES 没读到任何 subdomain" >&2; exit 1; }

names=()
for sub in "${subs[@]}"; do names+=("${sub}.${domain}"); done

snippet="# --- orgflow-devops gateway (generated by scripts/gen-hosts.sh) ---
${ip} ${names[*]}
# --- end orgflow-devops ---"

if (( write )); then
    target=/etc/hosts
    if [[ ! -w "$target" ]]; then
        echo "无写权限，请用 sudo 运行：sudo scripts/gen-hosts.sh $ip --write" >&2
        exit 1
    fi
    # 先删旧块，再追加，避免重复
    tmp="$(mktemp)"
    sed '/# --- orgflow-devops gateway/,/# --- end orgflow-devops ---/d' "$target" > "$tmp"
    printf '%s\n' "$snippet" >> "$tmp"
    cat "$tmp" > "$target"
    rm -f "$tmp"
    echo "已写入 $target（IP=$ip，域名=${#names[@]} 个）"
else
    printf '%s\n' "$snippet"
    echo
    echo "# 写入本机：sudo scripts/gen-hosts.sh $ip --write" >&2
    echo "# 局域网其他机器：把上面那行加到它的 /etc/hosts（Windows: C:\\Windows\\System32\\drivers\\etc\\hosts）" >&2
fi
