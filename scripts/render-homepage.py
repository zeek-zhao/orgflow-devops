#!/usr/bin/env python3
"""render-homepage.py —— manifest 驱动渲染 config/homepage/services.yaml（M0 R6）。

唯一真源是 services/manifest.tsv；本脚本生成两组卡片：
  分组一「服务状态」：内网探测卡，href 指向各自 public_path，保留 siteMonitor/ping。
  分组二「公网入口」：真正能点进去的路径入口，禁止「点进去还是 /status」的假入口。

公网入口组筛选规则（写进代码，不写死服务名）：
  public_path 既不是 /status 也不是 /none 的服务才会进组；
  另外固定追加一张「状态总览 → /status」卡（它代表状态页入口本身，不是假入口）。
  以后新增服务只要 manifest 的 public_path 是真实路径就会自动进组，无需手改本脚本。

manifest.tags 列保留供后续筛选，但不参与渲染：官方 gethomepage v2.7.0 的
services schema 无 tags 字段（已查证 https://gethomepage.dev/configs/services/），
R6 起彻底移除 [lan]/[domain]/[NO-UI] 方括号前缀，description 统一为
「一句中文用途 · 协议/端口」。

用法：
  python3 scripts/render-homepage.py            # 渲染写入 config/homepage/services.yaml
  python3 scripts/render-homepage.py --check     # 不一致返回非 0（进 make check / CI）
  python3 scripts/render-homepage.py --stdout    # 只打印，不写文件
"""
import csv
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MANIFEST = os.path.join(ROOT, "services", "manifest.tsv")
OUTPUT = os.path.join(ROOT, "config", "homepage", "services.yaml")
GENERATED = "# GENERATED BY scripts/render-homepage.py —— 禁止手改，改 services/manifest.tsv"

# 展示元数据（非注册信息）：名称 / 图标 / 一句中文用途 · 协议或端口。
# 新增服务只需在 manifest 加一行；这里给默认名/图标，需更友好文案时再补一条。
# 名称/图标不是「配置字面域名」，不违反 C-2。
META = {
    "homepage":   ("统一入口",  "mdi-home",            "服务导航与状态总览 · homepage:3000"),
    "ldapadmin":  ("LDAP 管理", "mdi-account-group",   "用户与部门管理 · 需登录"),
    "router":     ("路由服务",  "mdi-lan",             "动态路由注册与热更新 · router:8080"),
    "caddy":      ("Caddy 网关", "mdi-web",            "反向代理入口 · 管理端口仅内网"),
    "ldap":       ("LDAP 目录", "mdi-shield-account", "统一身份目录 · ldap:389"),
    "dnsmasq":    ("DNS 解析",  "mdi-dns",             "内网 DNS 服务 · UDP 53/5353"),
    "certs-init": ("证书初始化", "mdi-certificate",     "一次性任务 · 不放假页面"),
    "jenkins":    ("Jenkins",   "mdi-jenkins",         "持续集成与流水线 · jenkins:8080"),
    "jenkins-agent": ("Jenkins Agent", "mdi-ssh",      "构建执行节点 · 普通用户 jenkins / SSH 22"),
    "gerrit":     ("Gerrit",     "mdi-source-review",  "代码评审与 Git 服务 · gerrit:8080"),
    "cgit":       ("cgit",       "mdi-git",            "Gerrit 裸库只读视图 · /cgit/"),
    # M2.2 P2-3：registry 无 Web UI，文案明确「API only」并给出入口端口，
    # 避免用户误以为点卡片能进管理界面（服务状态组 href 统一落 /status，见 STATUS_HREF_PATH）。
    "registry":   ("镜像仓库 registry", "mdi-package-variant", "镜像仓库 API only · 公网 :10000 / 内网 :18086（无 Web UI）"),
}

# 公网入口组排除的 public_path：指向 /status 的假入口与一次性任务的 /none
NON_ENTRY_PATHS = {"/status", "/none"}

# 独立 Funnel 端口的服务入口：Gerrit 走 :8443（不在 443 门面 path 路由里）。
# 用 homepage VAR 占位符拼完整 URL，端口来自 defaults.env 的 FUNNEL_PORT_GERRIT，
# 不写死字面域名/端口（C-2）。compose 注入 HOMEPAGE_VAR_GERRIT_PORT。
ENTRY_OVERRIDE = {
    "gerrit": "https://{{HOMEPAGE_VAR_PUBLIC_HOST}}:{{HOMEPAGE_VAR_GERRIT_PORT}}/",
}

# 固定追加的入口卡：代表状态页入口本身（与 R6 删除的三张假入口不同，它是唯一并名的 /status 卡）
STATUS_CARD = ("状态总览", "mdi-chart-line", "全部服务入口与探测说明", "/status")

# 服务状态组统一落点：该组是「探测卡」（靠 siteMonitor/ping 展示健康），不是第二套入口。
# 历史 bug：服务状态组直接用 public_href，导致 (a) public_path=/none 的服务渲染成
# https://HOST/none 死链（jenkins-agent/gerrit）；(b) cgit 等真实 URL 在两组各出现一次
# 「链接重复 2 次」。真实可点入口只在「公网入口」组，状态卡一律点进状态总览。
STATUS_HREF_PATH = "/status"


def load_manifest():
    rows = []
    with open(MANIFEST, encoding="utf-8-sig") as f:
        reader = csv.DictReader(f, delimiter="\t")
        for r in reader:
            if not r.get("service"):
                continue
            # 错位防护：任一单元格为 None（列数不足）或出现 None 键（列数超表头）即报错
            if None in r or any(v is None for v in r.values()):
                raise SystemExit(f"✗ manifest 行 {r.get('service', '?')} 列数与表头不符（应为 9 列）")
            rows.append(r)
    rows.sort(key=lambda r: int(r["order"]))
    return rows


def q(s):
    """YAML 值加双引号并转义内部双引号。"""
    return '"' + (s or "").replace('"', '\\"') + '"'


def public_href(row):
    """public_path 规整为以 / 开头的 https://{{HOMEPAGE_VAR_PUBLIC_HOST}}<path>。"""
    path = (row.get("public_path") or "").strip()
    if not path.startswith("/"):
        path = "/" + path.lstrip("/")
    return "https://{{HOMEPAGE_VAR_PUBLIC_HOST}}" + path


def is_public_entry(row):
    """公网入口判定：public_path 既不是 /status 也不是 /none（不写死服务名）。"""
    return (row.get("public_path") or "").strip() not in NON_ENTRY_PATHS


def card_lines(name, icon, href, description, monitor="", ping=""):
    lines = [
        f"    - {name}:",
        f"        href: {q(href)}",
        f"        description: {q(description)}",
        f"        icon: {q(icon)}",
    ]
    if monitor:
        lines.append(f"        siteMonitor: {q(monitor)}")
    if ping:
        lines.append(f"        ping: {q(ping)}")
    return lines


def render(rows):
    out = [
        GENERATED,
        "# 由 services/manifest.tsv 渲染；tags 列保留供后续筛选，不参与展示（HomePage v2.7.0 无 tags 字段）。",
        "# 域名一律用 {{HOMEPAGE_VAR_PUBLIC_HOST}} 占位，运行时由 compose 注入，禁止字面域名。",
    ]
    # 分组一：服务状态（排除 certs-init 一次性任务），内网探测卡全保留（6 张）
    out.append("- 服务状态:")
    for r in rows:
        svc = r["service"]
        if svc == "certs-init":
            continue
        name, icon, note = META.get(svc, (svc, "mdi-circle", svc))
        # manifest 表头为 monitor_url_doc / ping_url_doc（r5 §4-5 定义的文档元数据列）。
        # 原脚本误读 monitor_url/ping_url（不存在的列）→ 渲染丢监控字段；此处修正列名。
        # href 统一落 /status：探测卡不是入口，避免 /none 死链与真实 URL 重复。
        status_href = "https://{{HOMEPAGE_VAR_PUBLIC_HOST}}" + STATUS_HREF_PATH
        out += card_lines(name, icon, status_href, note,
                          r.get("monitor_url_doc", ""), r.get("ping_url_doc", ""))
    # 分组二：公网入口（排除 certs-init），按 public_path 规则筛选真实入口。
    # 独立 Funnel 端口服务（ENTRY_OVERRIDE，如 gerrit:8443）即使 public_path=/none
    # 也纳入，用完整占位符 URL 表达独立端口入口（复核：Gerrit 无主页入口）。
    out.append("- 公网入口:")
    for r in rows:
        svc = r["service"]
        if svc == "certs-init":
            continue
        if svc in ENTRY_OVERRIDE:
            href = ENTRY_OVERRIDE[svc]
        elif is_public_entry(r):
            href = public_href(r)
        else:
            continue
        name, icon, note = META.get(svc, (svc, "mdi-circle", svc))
        out += card_lines(name, icon, href, note)
    # 状态总览：代表 /status 页入口本身（唯一一张 /status 卡，不是重复假入口）
    name, icon, note, path = STATUS_CARD
    out += card_lines(name, icon, "https://{{HOMEPAGE_VAR_PUBLIC_HOST}}" + path, note)
    return "\n".join(out) + "\n"


def main():
    text = render(load_manifest())
    args = set(sys.argv[1:])
    if "--stdout" in args:
        sys.stdout.write(text)
        return 0
    if "--check" in args:
        if not os.path.exists(OUTPUT):
            print(f"✗ 缺 {OUTPUT}", file=sys.stderr)
            return 1
        cur = open(OUTPUT, encoding="utf-8").read()
        if cur != text:
            print("✗ services.yaml 与 manifest 不一致，请运行 render-homepage.py", file=sys.stderr)
            return 1
        print("✓ services.yaml 与 manifest 一致")
        return 0
    with open(OUTPUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"✓ 已渲染 {OUTPUT}（{len(text.splitlines())} 行）")
    return 0


if __name__ == "__main__":
    sys.exit(main())
