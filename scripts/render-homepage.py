#!/usr/bin/env python3
"""render-homepage.py —— manifest 驱动渲染 config/homepage/services.yaml（M0-v2 R1/R2）。

唯一真源是 services/manifest.tsv；本脚本生成两组卡片：
  分组一「局域网服务状态」：状态来自容器内网探测，description 前缀 [LAN]
  分组二「域名入口」：href = https://{{HOMEPAGE_VAR_PUBLIC_HOST}}<public_path>，前缀 [DOMAIN]

标签语义（R3 查证结论，2026-11-24）：官方 gethomepage v2.7.0 的 services.yaml
字段清单**没有 tags 字段**（已查证 https://gethomepage.dev/configs/services/：
仅 href/description/icon/ping/siteMonitor/widget/group 等，无 tags；weight 由顺序隐式生成）。
故按 M0 收口提示词 R3 的降级方案：manifest.tags 列（值 lan,domain）不再被忽略，
渲染为 description 前缀 [lan][domain] + 保留分组名与 [NO-UI] 标记；不写 services.yaml 的 tags 字段。
两组卡片数量与顺序由 manifest order 决定，每组 6 张，不得变化。

用法：
  python3 scripts/render-homepage.py            # 渲染写入 config/homepage/services.yaml
  python3 scripts/render-homepage.py --check     # 不一致返回非 0（进 make check / CI）
  python3 scripts/render-homepage.py --stdout    # 只打印，不写文件
"""
import csv
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MANIFEST = os.path.join(ROOT, "services", "manifest.tsv")
OUTPUT = os.path.join(ROOT, "config", "homepage", "services.yaml")
GENERATED = "# GENERATED BY scripts/render-homepage.py —— 禁止手改，改 services/manifest.tsv"

# 展示元数据（非注册信息）：新增服务只需在 manifest 加一行；这里给默认名/图标，
# 需要更友好文案时再补一条。名称/图标不是"配置字面域名"，不违反 C-2。
META = {
    "homepage":  ("统一面板",   "mdi-home",           "统一导航面板 · homepage:3000"),
    "ldapadmin": ("LDAP 管理页", "mdi-account-group",  "用户与部门管理 · ldapadmin:80 · 需登录"),
    "router":    ("路由状态",   "mdi-lan",            "路由注册与热更新 · router:8080"),
    "caddy":     ("Caddy 网关", "mdi-web",            "反向代理入口 · admin 仅内网 · 无独立 Web UI，见状态页"),
    "ldap":      ("LDAP 目录",  "mdi-shield-account", "身份目录 · ldap:389 · ICMP 探容器 + verify.sh 探 389 · 无独立 Web UI，见状态页"),
    "dnsmasq":   ("DNS 解析",   "mdi-dns",            "容器内 DNS · 无 HTTP 端点 · TCP/ICMP 探测 · 无独立 Web UI，见状态页"),
    "certs-init":("证书初始化", "mdi-certificate",    "一次性任务 · 不放假页面"),
}

# 修复轮 T5：3 个无独立 Web UI 的服务，域名入口卡前缀 [NO-UI]、落点 /status（由 manifest public_path 指定）
NO_UI = {"dnsmasq", "ldap", "caddy"}


def load_manifest():
    rows = []
    with open(MANIFEST, encoding="utf-8-sig") as f:
        reader = csv.DictReader(f, delimiter="\t")
        for r in reader:
            if not r.get("service"):
                continue
            # 错位防护：任一单元格为 None（列数不足）或出现 None 键（列数超表头）即报错
            if None in r or any(v is None for v in r.values()):
                raise SystemExit(f"✗ manifest 行 {r.get('service', '?')} 列数与表头不符（应为 9 列）")
            rows.append(r)
    rows.sort(key=lambda r: int(r["order"]))
    return rows


def q(s):
    """YAML 值加双引号并转义内部双引号。"""
    return '"' + (s or "").replace('"', '\\"') + '"'


def tags_prefix(row):
    """R3：把 manifest.tags 列（如 'lan,domain'）渲染为 '[lan][domain]' 前缀。
    HomePage services schema 无 tags 字段，降级为 description 前缀（见顶部注释）。"""
    tags = [t.strip() for t in (row.get("tags") or "").split(",") if t.strip()]
    return "".join(f"[{t}]" for t in tags)


def card_lines(name, icon, href, description, monitor="", ping=""):
    lines = [
        f"    - {name}:",
        f"        href: {q(href)}",
        f"        description: {q(description)}",
        f"        icon: {q(icon)}",
    ]
    if monitor:
        lines.append(f"        siteMonitor: {q(monitor)}")
    if ping:
        lines.append(f"        ping: {q(ping)}")
    return lines


def render(rows):
    out = [
        GENERATED,
        "# 由 services/manifest.tsv 渲染；tags 列降级为 description 前缀 [lan][domain]，分组名 + [LAN]/[DOMAIN]/[NO-UI] 保留。",
        "# 域名一律用 {{HOMEPAGE_VAR_PUBLIC_HOST}} 占位，运行时由 compose 注入，禁止字面域名。",
    ]
    # 分组一：局域网服务状态（排除 certs-init 一次性任务）
    out += ["- 局域网服务状态:"]
    for r in rows:
        svc = r["service"]
        if svc == "certs-init":
            continue
        name, icon, note = META.get(svc, (svc, "mdi-circle", svc))
        href = "{{HOMEPAGE_VAR_PUBLIC_HOST}}" + r["public_path"].lstrip(".")
        # 公网入口路径以 / 开头；/status 也是 Caddy 探针，合法
        if not href.startswith("{{HOMEPAGE_VAR_PUBLIC_HOST}}/"):
            href = "{{HOMEPAGE_VAR_PUBLIC_HOST}}/" + r["public_path"].strip("/")
        desc = tags_prefix(r) + "[LAN] " + note
        out += card_lines(name, icon, "https://" + href, desc,
                          r.get("monitor_url", ""), r.get("ping_url", ""))
    # 分组二：域名入口（排除 certs-init）
    # 修复轮 T5：真实入口 = [DOMAIN]；3 个无 UI 服务 = [NO-UI]，href 由 manifest public_path 指向 /status
    out += ["- 域名入口:"]
    for r in rows:
        svc = r["service"]
        if svc == "certs-init":
            continue
        name, icon, note = META.get(svc, (svc, "mdi-circle", svc))
        path = r["public_path"]
        if not path.startswith("/"):
            path = "/" + path.lstrip("/")
        flag = "[NO-UI] " if svc in NO_UI else "[DOMAIN] "
        desc = tags_prefix(r) + flag + note
        out += card_lines(name, icon, "https://{{HOMEPAGE_VAR_PUBLIC_HOST}}" + path,
                          desc)
    return "\n".join(out) + "\n"


def main():
    text = render(load_manifest())
    args = set(sys.argv[1:])
    if "--stdout" in args:
        sys.stdout.write(text)
        return 0
    if "--check" in args:
        if not os.path.exists(OUTPUT):
            print(f"✗ 缺 {OUTPUT}", file=sys.stderr)
            return 1
        cur = open(OUTPUT, encoding="utf-8").read()
        if cur != text:
            print("✗ services.yaml 与 manifest 不一致，请运行 render-homepage.py", file=sys.stderr)
            return 1
        print("✓ services.yaml 与 manifest 一致")
        return 0
    with open(OUTPUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"✓ 已渲染 {OUTPUT}（{len(text.splitlines())} 行）")
    return 0


if __name__ == "__main__":
    sys.exit(main())
